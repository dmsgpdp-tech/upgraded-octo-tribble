import type { SajuResult } from "@/lib/saju/types";

export const SYSTEM_PROMPT = `당신은 따뜻하고 통찰력 있는 한국 명리학(사주) 해설가입니다.

원칙:
- 사주 데이터는 만세력 프로그램이 이미 정확히 계산해서 JSON으로 줍니다. 간지·십신·대운을 직접 다시 계산하거나 바꾸지 말고, 주어진 값만 근거로 풀이하세요.
- 시주가 null이면 태어난 시간을 모르는 것입니다. 시주 없이 풀이하고, 시주가 없어 덜 정확할 수 있는 부분은 짧게 언급하세요.
- 한국어로, 일반인이 이해할 수 있게 쉽게 쓰세요. 전문 용어(예: 편관, 식신)를 쓰면 괄호로 짧게 뜻을 풀어 주세요.
- 마크다운으로 읽기 좋게 작성하세요 (## 소제목, 굵게, 목록).
- 겁을 주거나 단정하는 표현(예: "반드시 망한다", "단명")은 피하고, 주의점은 조언 형태로 말하세요.
- 건강·법률·투자 같은 중요한 결정은 사주만으로 판단하지 말라고 필요할 때 짧게 덧붙이세요.`;

export function buildInitialPrompt(saju: SajuResult): string {
  // 풀이에 필요 없는 입력 옵션은 빼고 전달한다.
  const { input, ...data } = saju;
  const payload = { 성별: input.gender === "male" ? "남" : "여", 출생지: input.placeName, ...data };

  return `다음은 한 사람의 사주 계산 결과입니다.

\`\`\`json
${JSON.stringify(payload, null, 2)}
\`\`\`

아래 순서로 사주를 풀이해 주세요.

## 1. 한눈에 보는 사주
일간(나를 상징하는 글자)과 전체적인 인상을 3~4문장으로.

## 2. 타고난 성격과 기질
일간, 월지, 십신 구성을 바탕으로 장점과 약점.

## 3. 오행의 균형
많은 오행·부족한 오행이 삶에 어떻게 드러나는지, 보완 방법(색, 방향, 습관 등).

## 4. 적성과 일
어울리는 일의 방식과 분야.

## 5. 대운의 흐름
지금까지와 현재 대운(current), 앞으로의 대운 흐름을 시기별로 간단히.

## 6. ${saju.currentYear.year}년 운세
올해 세운과 현재 대운을 함께 보고 올해의 흐름과 조언.

## 7. 한마디 조언
따뜻한 응원과 함께 마무리.`;
}
